/// Directly tests compute_multi_input_rhs (the else branch at lib.rs lines 672-690)
/// with outer_inputs_len = 0x40 (2 input sets).
#[test]
fn compute_multi_input_rhs_with_two_inputs() {
    use crate::types::Fr;

    // Memory layout: fmp at 0x40 points to 0x100.
    // At fmp+0x00 (0x100): l_blind value
    // At fmp+0x20 (0x120): tmp1 value
    // At fmp+0x40 (0x140): l_last value
    // At fmp+0x80 (0x180): beta accum
    // At fmp+0xa0 (0x1a0): input[0] value
    // At fmp+0xc0 (0x1c0): input[1] value
    let fmp: u32 = 0x100;
    let mut memory = vec![0u8; 0x200];

    // Store fmp at 0x40
    let fmp_bytes = (fmp as u64).to_be_bytes();
    memory[0x40 + 24..0x40 + 32].copy_from_slice(&fmp_bytes);

    // Store field elements at the required offsets
    let val_a = Fr::from(3u64); // input[0] at fmp+0xa0
    let val_b = Fr::from(5u64); // input[1] at fmp+0xc0
    let table = Fr::from(7u64);

    let a_bytes = crate::utils::IntoBEBytes32::into_be_bytes32(val_a);
    let b_bytes = crate::utils::IntoBEBytes32::into_be_bytes32(val_b);

    let offset_a = (fmp + 0xa0) as usize;
    let offset_b = (fmp + 0xc0) as usize;
    memory[offset_a..offset_a + 32].copy_from_slice(&a_bytes);
    memory[offset_b..offset_b + 32].copy_from_slice(&b_bytes);

    let result = crate::compute_multi_input_rhs(&mut memory, fmp, 0x40, table).unwrap();

    // With outer_inputs_len=0x40 (2 inputs, i=0x00 and i=0x20):
    // i=0: tmp = input[1] (0xc0), skip j where i==j. j starts at 0x40 (>0x40 false), so no multiply. rhs += input[1] = 5
    // i=0x20 (last_idx): tmp = input[0] (0xa0), j=0x20, skip i==j, j+=0x20 -> j=0x40 >= 0x40 done. rhs += input[0] = 5+3=8. rhs *= table = 8*7 = 56
    let expected = (val_b + val_a) * table;
    assert_eq!(result, expected);
}

/// Directly tests compute_multi_input_rhs with outer_inputs_len = 0x60 (3 input sets).
/// This exercises the inner multiply loop (the `if i != j` branch).
#[test]
fn compute_multi_input_rhs_with_three_inputs() {
    use crate::types::Fr;

    let fmp: u32 = 0x100;
    let mut memory = vec![0u8; 0x300];

    // Store fmp at 0x40
    let fmp_bytes = (fmp as u64).to_be_bytes();
    memory[0x40 + 24..0x40 + 32].copy_from_slice(&fmp_bytes);

    let val_a = Fr::from(3u64); // input[0] at fmp+0xa0
    let val_b = Fr::from(5u64); // input[1] at fmp+0xc0
    let val_c = Fr::from(11u64); // input[2] at fmp+0xe0
    let table = Fr::from(7u64);

    let a_bytes = crate::utils::IntoBEBytes32::into_be_bytes32(val_a);
    let b_bytes = crate::utils::IntoBEBytes32::into_be_bytes32(val_b);
    let c_bytes = crate::utils::IntoBEBytes32::into_be_bytes32(val_c);

    let offset_a = (fmp + 0xa0) as usize;
    let offset_b = (fmp + 0xc0) as usize;
    let offset_c = (fmp + 0xe0) as usize;
    memory[offset_a..offset_a + 32].copy_from_slice(&a_bytes);
    memory[offset_b..offset_b + 32].copy_from_slice(&b_bytes);
    memory[offset_c..offset_c + 32].copy_from_slice(&c_bytes);

    let result = crate::compute_multi_input_rhs(&mut memory, fmp, 0x60, table).unwrap();

    // With 3 inputs (a, b, c):
    // i=0x00: tmp = b (loaded from 0xc0), j starts at 0x40, j=0x40 != 0x00 → tmp *= c. rhs += b*c
    // i=0x20: tmp = a (loaded from 0xa0), j=0x20 == i skip, j=0x40 → tmp *= c. rhs += a*c
    // i=0x40 (last_idx): tmp = a (loaded from 0xa0), j=0x20 → tmp *= b, j=0x40 == i skip. rhs += a*b. rhs *= table
    // rhs = (b*c + a*c + a*b) * table
    let expected = (val_b * val_c + val_a * val_c + val_a * val_b) * table;
    assert_eq!(result, expected);
}

